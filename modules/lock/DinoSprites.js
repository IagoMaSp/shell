function text(str) {
    var rows = ["", "", "", "", ""];
    for (var i = 0; i < str.length; i++) {
        var glyph = glyphs[str[i]] || glyphs[" "];
        for (var r = 0; r < 5; r++)
            rows[r] += glyph[r] + ".";
    }
    return rows;
}
