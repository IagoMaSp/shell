#!/usr/bin/env python3
"""Writes the Hallownest Thunar CSS over the one caelestia generates (run after `caelestia scheme set`)."""
import os
import sys
from pathlib import Path

ACCENTS = {"vessel": "#f0f4f8", "lifeblood": "#6cc9ff", "infection": "#ff8a2a", "greenpath": "#74c98a"}
STEELS = {"vessel": "#9ba4b5", "lifeblood": "#8fb3cc", "infection": "#b8a08f", "greenpath": "#94b39c"}
POINTER = '<svg xmlns="http://www.w3.org/2000/svg" width="19" height="8" viewBox="{} 0 19 8"><path fill="{}" d="{}"/></svg>'
LEFT = "M0 4 L4 0 L8 4 L4 8 Z M9 3 L16 3.6 L16 4.4 L9 5 Z"
RIGHT = "M16 4 L12 0 L8 4 L12 8 Z M7 3 L0 3.6 L0 4.4 L7 5 Z"

flavour = sys.argv[1] if len(sys.argv) > 1 and sys.argv[1] in ACCENTS else "vessel"
assets = Path(__file__).parent
gtk = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config") / "gtk-3.0"
images = gtk / "hallownest"
images.mkdir(parents=True, exist_ok=True)

accent = ACCENTS[flavour]
(images / "pointer-left.svg").write_text(POINTER.format(-3, accent, LEFT))
(images / "pointer-right.svg").write_text(POINTER.format(0, accent, RIGHT))

css = f"""/* Generated by paleshell/assets/thunar-theme.py ({flavour}); edit assets/thunar/hallownest.css instead */
@define-color hk_accent {accent};
@define-color hk_steel {STEELS[flavour]};

""" + (assets / "thunar" / "hallownest.css").read_text()
(gtk / "thunar.css").write_text(css)
